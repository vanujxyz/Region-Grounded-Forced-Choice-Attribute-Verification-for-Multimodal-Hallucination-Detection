# ---- Table: pair outcomes ------------------------------------------------------
def pair_out(stem):
    by = defaultdict(dict)
    for line in read_lines(RAW / f"{stem}.jsonl"):
        r = json.loads(line)
        by[(r["image"], tuple(r["triple"]))][r["gold"]] = r["pred"]
    c = Counter()
    m = {("yes", "no"): "correct", ("yes", "yes"): "both_yes", ("no", "no"): "both_no", ("no", "yes"): "reversed"}
    for v in by.values():
        c[m[(v["yes"], v["no"])]] += 1
    return c


