f4 = lambda v: f"{v:.4f}"
sg = lambda v: f"{v:+.4f}".replace("-", "$-$") if False else (f"$+{v:.4f}$" if v >= 0 else f"$-{abs(v):.4f}$")
ci = lambda lo, hi: f"$[{lo:+.4f},\\,{hi:+.4f}]$".replace("+-", "-")
pct = lambda v: f"{100 * v:.1f}\\%"


def vcell(split, cell, typ="all"):
    d = vc[split]
    return d[(d.cell == cell) & (d.type == typ)].iloc[0]


def vcon(split, comp, typ="all"):
    d = vk[split]
    return d[(d.comparison == comp) & (d.type == typ)].iloc[0]


def acell(ds, cell):
    d = at[ds]
    return d[d.cell == cell].iloc[0]


def acon(ds, comp):
    d = ak[ds]
    return d[d.comparison == comp].iloc[0]


